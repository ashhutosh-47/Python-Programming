# in -> Check for Membership
# This operators returns True if the specified value is found within the list and False otherwise
fruits = ["apple", "banana", "cherry"]

print("banana" in fruits) # True
print("grape" in fruits) # False

# not in -> Check for Non-Membership
# This operators returns True if the specified value is NOT found within the list and False otherwise
fruits = ["apple", "banana", "cherry"]
print("banana" not in fruits) # False
print("grape" not in fruits) # True



